function t(key) {
  const dict = I18N[LANG] || I18N.en;
  let val = dict[key];
  if (val === undefined) val = I18N.en[key];
  if (val === undefined) return key;
  if (typeof val === "function") return val.apply(null, Array.prototype.slice.call(arguments, 1));
  return val;
}
